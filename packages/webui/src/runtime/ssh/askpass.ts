// The askpass helper: how a staged password reaches OpenSSH without ever being on disk.
//
// OpenSSH asks for a password by running the program named in `SSH_ASKPASS`. That program has to
// answer with the password, so the password has to reach it somehow. Desktop solves this with a
// socket and a helper process; this port does the same, and for the same reason: the password
// stays in this process's memory.
//
// The pieces:
//
//   * `askpass.cjs` — the helper. It is a plain CommonJS file: it reads the socket path and the
//     token from its environment, asks the service for the password, and writes the answer to its
//     standard output. It holds no secret of its own.
//   * `askpass.sh` — the shell wrapper OpenSSH executes, which runs the helper with this
//     process's own node binary.
//   * a unix socket — the service's answer. A request carries the token and the host alias; a
//     request without the right token is answered with an empty line, so a process that guesses
//     the socket path learns nothing.
//
// Windows has no POSIX shell to run the wrapper, so the password path is POSIX-only. A Windows
// host that is handed a password is told the credential is unavailable rather than silently
// dropping it.
import { randomBytes } from "node:crypto";
import { chmod, mkdir, writeFile } from "node:fs/promises";
import { createServer, type Server, type Socket } from "node:net";
import path from "node:path";

import type { SshCredentialStore } from "./credentials.js";
import { SshRuntimeError } from "./errors.js";

const HELPER_SOURCE = `"use strict";
// Generated by the WebUI SSH runtime. It holds no credential: it asks the
// service over a unix socket and prints what the service answers.
const net = require("node:net");
const socketPath = process.env.MAVIS_SSH_ASKPASS_SOCKET;
const token = process.env.MAVIS_SSH_ASKPASS_TOKEN;
const alias = process.env.MAVIS_SSH_ASKPASS_ALIAS;
const prompt = process.argv[2] || "";
if (!socketPath || !token) {
  process.stdout.write("\\n");
  process.exit(0);
}
const socket = net.createConnection(socketPath);
let answered = false;
socket.on("connect", () => {
  socket.write(JSON.stringify({ token, alias, prompt }) + "\\n");
});
socket.on("data", (chunk) => {
  answered = true;
  process.stdout.write(chunk.toString("utf8"), () => socket.end());
});
socket.on("error", () => {
  if (!answered) process.stdout.write("\\n");
  process.exit(1);
});
socket.on("close", () => process.exit(0));
`;

const WRAPPER_SOURCE = (nodePath: string, helperPath: string): string =>
  ["#!/bin/sh", `exec ${JSON.stringify(nodePath)} ${JSON.stringify(helperPath)} "$@"`, ""].join("\n");

export interface SshAskpassService {
  /** The environment an `ssh` child needs so OpenSSH asks this service. */
  readonly env: Record<string, string>;
  /** The environment one `ssh` child needs for one host. */
  envFor(alias: string): Record<string, string>;
  dispose(): Promise<void>;
}

export interface CreateSshAskpassServiceOptions {
  /** The directory the helper files and the socket live in. */
  readonly rootDir: string;
  readonly credentials: SshCredentialStore;
}

export async function createSshAskpassService(
  options: CreateSshAskpassServiceOptions,
): Promise<SshAskpassService> {
  if (process.platform === "win32") {
    throw new SshRuntimeError(
      "credential_unavailable",
      "当前平台不支持 SSH 密码登录：缺少可运行的 askpass 助手。",
    );
  }

  const helperDir = path.join(options.rootDir, "askpass");
  const helperPath = path.join(helperDir, "askpass.cjs");
  const wrapperPath = path.join(helperDir, "askpass.sh");
  const socketPath = path.join(helperDir, "askpass.sock");
  const token = randomBytes(24).toString("hex");

  await mkdir(helperDir, { recursive: true, mode: 0o700 });
  await writeFile(helperPath, HELPER_SOURCE, { mode: 0o700 });
  await writeFile(wrapperPath, WRAPPER_SOURCE(process.execPath, helperPath), { mode: 0o700 });
  await chmod(helperPath, 0o700);
  await chmod(wrapperPath, 0o700);

  const server: Server = createServer((socket: Socket) => {
    let buffer = "";
    socket.setEncoding("utf8");
    socket.on("data", (chunk: string) => {
      buffer += chunk;
      const newline = buffer.indexOf("\n");
      if (newline < 0) return;
      const line = buffer.slice(0, newline);
      buffer = buffer.slice(newline + 1);
      let answer = "\n";
      try {
        const request = JSON.parse(line) as { token?: string; alias?: string };
        if (request.token === token && typeof request.alias === "string") {
          const password = options.credentials.get(request.alias);
          if (password !== undefined) answer = `${password}\n`;
        }
      } catch {
        answer = "\n";
      }
      socket.write(answer);
    });
    socket.on("error", () => socket.destroy());
  });

  await new Promise<void>((resolve, reject) => {
    server.once("error", reject);
    server.listen(socketPath, () => resolve());
  });

  const baseEnv: Record<string, string> = {
    SSH_ASKPASS: wrapperPath,
    SSH_ASKPASS_REQUIRE: "force",
    MAVIS_SSH_ASKPASS_SOCKET: socketPath,
    MAVIS_SSH_ASKPASS_TOKEN: token,
  };

  return {
    env: baseEnv,
    envFor: (alias) => ({ ...baseEnv, MAVIS_SSH_ASKPASS_ALIAS: alias }),
    dispose: async () => {
      await new Promise<void>((resolve) => server.close(() => resolve()));
    },
  };
}
