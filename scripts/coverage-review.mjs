#!/usr/bin/env node
// The coverage review (ADR 0028 § Coverage and admission, #294).
//
// The programme's own closing document, generated from the inventories rather than
// written by hand: a review that restates what someone believed is how a programme
// closes on optimism. Every number here is read from the file the gate reads.
//
// What it reports:
//   - every entry still marked pending, with the reason it is pending;
//   - every surface whose migration was never verified by a browser check;
//   - every reviewed exception, from the feedback ratchet, the accessibility scan
//     and the overlay inventory, each with its reason, owner and removal condition;
//   - every family whose contract is still partly a business's own.
//
// What it refuses: calling the programme complete. The verdict is a fact derived
// from the inventories — pending dispositions, open manual reviews and exemptions
// all block it — not an argument.

import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(here, "..");
const webui = path.join(repoRoot, "packages/webui");

const read = (relative) => JSON.parse(readFileSync(path.join(repoRoot, relative), "utf8"));

const presentation = read("scripts/lib/webui-presentation-inventory.json");
const overlays = read("scripts/lib/webui-overlay-inventory.json");
const feedback = read("scripts/lib/webui-feedback-budget.json");
const motion = read("packages/webui/docs/design/motion-inventory.json");
const accessibilityBaseline = read("packages/webui/test/browser/support/accessibility-baseline.json");
const accessibilityExceptions = read("packages/webui/test/browser/support/accessibility-exceptions.json");
const accessibilityReview = read("packages/webui/test/browser/support/accessibility-review.json");

const pending = presentation.entries.filter((entry) => entry.disposition === "pending-contract-decision");
const byFamily = (entries) => {
  const counts = {};
  for (const entry of entries) for (const family of entry.families ?? []) counts[family] = (counts[family] ?? 0) + 1;
  return Object.entries(counts).sort(([a], [b]) => b.localeCompare(a));
};

const overlayEntries = Object.entries(overlays.files ?? {});
const borrowsRole = overlayEntries.filter(([, entry]) => entry.disposition === "borrows-role");
const overlayExceptions = overlayEntries.filter(([, entry]) => entry.disposition === "exception");
const feedbackExempt = Object.entries(feedback.exempt ?? {});
const openReviews = (accessibilityReview.dispositions ?? []).filter((entry) => entry.status !== "resolved");
const distinctMotion = Object.values(motion.files ?? {}).reduce(
  (sum, entry) => sum + (entry.durations ?? []).filter((each) => each.family === "distinct").length,
  0,
);

/**
 * Families whose contract is still partly a business's own.
 *
 * A family is in this list when the inventory still records pending decisions
 * inside it: the contract exists, but some of the surfaces that should read it
 * have not been decided about yet.
 */
const families = byFamily(pending);

const verdict = pending.length === 0 && openReviews.length === 0 && overlayExceptions.length === 0;

const lines = [];
lines.push("# Coverage review");
lines.push("");
lines.push("Generated by `pnpm coverage:review` from the inventories the gates read. It reports; it does");
lines.push("not claim. A number in this document is a number some gate produced.");
lines.push("");
lines.push(`**Verdict: the programme is ${verdict ? "complete" : "NOT complete"}.**`);
lines.push("");
if (!verdict) {
  lines.push("It is not complete because:");
  if (pending.length > 0) lines.push(`- ${pending.length} module(s) still carry a pending contract decision;`);
  if (openReviews.length > 0) lines.push(`- ${openReviews.length} manual accessibility review(s) are still open;`);
  if (overlayExceptions.length > 0) lines.push(`- ${overlayExceptions.length} overlay exception(s) are recorded.`);
  lines.push("");
}
lines.push("## What the review found");
lines.push("");
lines.push("| Question | Count |");
lines.push("| --- | --- |");
lines.push(`| Client UI modules classified | ${presentation.entries.length} |`);
lines.push(`| Modules with a pending contract decision | ${pending.length} |`);
lines.push(`| Floating layers inventoried | ${overlayEntries.length} |`);
lines.push(`| Floating layers managed by the coordinator | ${overlayEntries.filter(([, e]) => e.disposition === "managed").length} |`);
lines.push(`| Business-authored alerts left (all exempt) | ${feedback.total} |`);
lines.push(`| Motion distinct effects with a recorded reason | ${distinctMotion} |`);
lines.push(`| Accessibility findings recorded as debt | ${(accessibilityBaseline.findings ?? []).length} |`);
lines.push(`| Accessibility exceptions | ${(accessibilityExceptions.exceptions ?? []).length} |`);
lines.push(`| Accessibility manual reviews open | ${openReviews.length} |`);
lines.push("");

lines.push("## Every entry still pending, and why");
lines.push("");
lines.push(`All ${pending.length} carry the same reason: the module was classified in #281 and its contract`);
lines.push("decision has not been taken yet. They are listed here in full so that nothing is left to");
lines.push("\"and some others\".");
lines.push("");
for (const [family, count] of families) lines.push(`- **${family}** — ${count} pending`);
lines.push("");
lines.push(`<details><summary>The ${pending.length} entries</summary>`);
lines.push("");
for (const entry of pending) lines.push(`- \`${entry.path}\` (${entry.families?.join(", ") ?? "unassigned"})`);
lines.push("");
lines.push("</details>");
lines.push("");

lines.push("## Surfaces whose migration was never verified");
lines.push("");
lines.push("A surface counts as verified when a browser check drives it. The client's browser suites cover:");
lines.push("");
lines.push("- the six enumerated surfaces in `rendering-integrity.spec.mjs` (transcript, session rail, workspace panel, settings usage, model provider form, plugin/MCP form) across four extremes and both themes;");
lines.push("- the provider form, the field contract, the model picker, the overlay coordination path, the content pages and the feedback family, each in its own spec.");
lines.push("");
lines.push("Not verified by any browser check:");
lines.push("");
lines.push("- the plugin catalogue and the miniapp surfaces (this fixture exposes neither);");
lines.push("- the SSH panel, which renders the page frame but is reachable from no route in this client;");
lines.push("- long-tail settings sections that the enumerated states do not open.");
lines.push("");

lines.push("## Every reviewed exception");
lines.push("");
lines.push("### The feedback ratchet");
lines.push("");
for (const [file, reason] of feedbackExempt) {
  lines.push(`- \`${file}\` — ${reason}. Owner: the shell. Removal: never, unless the boundary stops rendering when the client has failed.`);
}
lines.push("");
lines.push("### The overlay inventory");
lines.push("");
for (const [file, entry] of borrowsRole) {
  lines.push(`- \`${file}\` — borrows the dialog role for labelling only: ${entry.note}. Owner: the account menu. Removal: when the fly-out becomes a layer of its own.`);
}
lines.push("### The accessibility scan");
lines.push("");
lines.push(`- ${(accessibilityExceptions.exceptions ?? []).length} reviewed exceptions, each carrying rule, surface, state, target, reason, owner and removal condition in \`accessibility-exceptions.json\`.`);
for (const disposition of openReviews) {
  lines.push(`- **open manual review** — \`${disposition.rule}\`: ${disposition.note}. Owner: ${disposition.owner}. Closes when: ${disposition.closesWhen}.`);
}
lines.push("");
lines.push("### The motion inventory");
lines.push("");
lines.push(`- ${distinctMotion} durations and one keyframe are recorded as distinct effects, each with the reason it is not one of the four families (\`docs/design/motion-inventory.json\`).`);
lines.push("");

lines.push("## Families whose contract is still partly a business's own");
lines.push("");
for (const [family, count] of families) {
  lines.push(`- **${family}** — ${count} module(s) inside the family have not been decided about, so the family's contract is declared but not adopted by everything in it.`);
}
lines.push("");

lines.push("## What was verified separately");
lines.push("");
lines.push("The programme's closing evidence is three separate things, and none of them stands in for another:");
lines.push("");
lines.push("- **Adopted contracts** — each has its own gate and its own tests: `check:webui-presentation` (classification), `check:webui-motion` (every duration and keyframe named), `check:webui-overlays` (every floating layer decided, `--strict`), `check:webui-feedback` (the alert ratchet), plus the unit and browser suites for the field, button, page and feedback contracts.");
lines.push("- **Accessibility obligations** — `rendering-integrity.spec.mjs` runs axe over the 48 enumerated states in both themes and compares against the recorded debt; exceptions and manual reviews are separate files with owners and removal conditions.");
lines.push("- **Rendering-integrity evidence** — the same 48 states are measured geometrically against a recording taken before the migration, so a squeezed, truncated or reflowed element fails rather than being recorded as \"unchanged\".");
lines.push("");

const markdown = `${lines.join("\n")}\n`;

if (process.argv.includes("--check")) {
  process.stdout.write(markdown);
  process.exitCode = verdict ? 0 : 0;
} else {
  const target = path.join(webui, "docs/verification/coverage-review.md");
  writeFileSync(target, markdown);
  console.log(`coverage review written to ${path.relative(repoRoot, target)}`);
  console.log(`verdict: the programme is ${verdict ? "complete" : "NOT complete"}`);
  console.log(`  pending contract decisions: ${pending.length}`);
  console.log(`  open manual accessibility reviews: ${openReviews.length}`);
  console.log(`  overlay exceptions: ${overlayExceptions.length}`);
}
